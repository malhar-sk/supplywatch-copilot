"""Build data/corpus/ (run on the host: `make corpus`).

1. REAL text: USGS Mineral Commodity Summaries (MCS) 2024 + 2025 PDFs for the
   10 materials, public domain (U.S. Government work), fetched without login.
   Each PDF is split into its standard sections; each section = one document.
2. SYNTHETIC: fictional supplier profiles + a fictional customer BOM written
   from scripts/suppliers_data.py (deterministic), and short fictional news
   items generated by an LLM (Haiku-class) about those fictional suppliers.
   Every synthetic document has `synthetic: true` in its header.

Document format: a small "key: value" header, a line with `---`, then text.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from datetime import date
from pathlib import Path

import httpx
import statistics

import pdfplumber

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
sys.path.insert(0, str(ROOT / "app"))
from suppliers_data import CUSTOMER, SUPPLIERS  # noqa: E402

CORPUS = ROOT / "data" / "corpus"
PDF_CACHE = ROOT / "data" / ".pdf_cache"  # gitignored
MATERIALS = {
    "lithium": "Lithium", "cobalt": "Cobalt", "nickel": "Nickel", "rare-earths": "Rare Earths",
    "gallium": "Gallium", "germanium": "Germanium", "graphite": "Graphite", "tungsten": "Tungsten",
    "antimony": "Antimony", "manganese": "Manganese",
}
YEARS = (2025, 2024)
SECTIONS = [
    ("Domestic Production and Use", "domestic-production-and-use"),
    ("Salient Statistics", "salient-statistics"),
    ("Recycling", "recycling-and-import-sources"),
    ("Government Stockpile", "government-stockpile"),
    ("Events, Trends, and Issues", "events-trends-and-issues"),
    ("World Mine Production", "world-production-and-reserves"),
    ("World Low-Purity Production", "world-production-and-reserves"),
    ("World Production", "world-production-and-reserves"),
    ("World Refinery Production", "world-production-and-reserves"),
    ("World Smelter Production", "world-production-and-reserves"),
    ("World Resources", "world-resources"),
    ("Substitutes", "substitutes"),
]
# sections we drop (low value for Q&A) - their text is cut out
DROP = ("Tariff", "Depletion Allowance")


def write_doc(path: Path, meta: dict, body: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    head = "\n".join(f"{k}: {json.dumps(v) if isinstance(v, (list, bool)) else v}" for k, v in meta.items())
    path.write_text(f"{head}\n---\n{body.strip()}\n", encoding="utf-8")


def pdf_text(path: Path) -> str:
    """Text of every page, dropping superscript characters (footnote markers and the
    'e' = estimated flag). pypdf fused those into table numbers, e.g. Australia's
    lithium reserves '5'+'7,000,000' -> '57,000,000'; filtering chars smaller than
    80% of the page's dominant font size fixes that."""
    pages = []
    with pdfplumber.open(str(path)) as pdf:
        for page in pdf.pages:
            body = statistics.mode(round(c["size"], 1) for c in page.chars)
            kept = page.filter(lambda o: o.get("object_type") != "char" or o["size"] >= body * 0.8)
            pages.append(kept.extract_text() or "")
    return "\n".join(pages)


def clean_pdf_text(text: str, material_upper: str) -> str:
    out = []
    for line in text.splitlines():
        s = line.strip()
        if not s or re.fullmatch(r"\d{1,3}", s):
            continue
        if s.startswith("Prepared by") or s.startswith("U.S. Geological Survey, Mineral Commodity Summaries"):
            continue
        if s.upper() == s and material_upper in s and len(s) < 40:
            continue
        out.append(s)
    text = "\n".join(out)
    text = re.sub(r"-\n(?=[a-z])", "", text)
    return text


def split_sections(text: str) -> dict[str, str]:
    pattern = "|".join(re.escape(h) for h, _ in SECTIONS) + "|" + "|".join(re.escape(d) for d in DROP)
    marks = [(m.start(), m.group(0)) for m in re.finditer(rf"(?m)^(?:{pattern})\b", text)]
    sections: dict[str, str] = {}
    for i, (pos, head) in enumerate(marks):
        end = marks[i + 1][0] if i + 1 < len(marks) else len(text)
        if head in DROP:
            continue
        slug = dict(SECTIONS)[head]
        body = text[pos:end].strip()
        # footnotes at the end of the PDF ("eEstimated. ...") are noise
        body = re.split(r"\n(?:e|E)stimated\.", body)[0]
        sections[slug] = (sections.get(slug, "") + "\n" + body).strip()
    return sections


def build_usgs(fetch_date: str) -> int:
    PDF_CACHE.mkdir(parents=True, exist_ok=True)
    n = 0
    with httpx.Client(timeout=60, follow_redirects=True) as client:
        for year in YEARS:
            for slug, name in MATERIALS.items():
                url = f"https://pubs.usgs.gov/periodicals/mcs{year}/mcs{year}-{slug}.pdf"
                pdf = PDF_CACHE / f"mcs{year}-{slug}.pdf"
                if not pdf.exists():
                    r = client.get(url)
                    r.raise_for_status()
                    pdf.write_bytes(r.content)
                raw = pdf_text(pdf)
                upper = name.upper().replace("RARE EARTHS", "RARE EARTH")
                text = clean_pdf_text(raw, upper)
                for sec_slug, body in split_sections(text).items():
                    if len(body) < 40:
                        continue
                    title = f"USGS MCS {year} - {name} - {sec_slug.replace('-', ' ').title()}"
                    doc_id = f"usgs-{year}-{slug}-{sec_slug}"
                    write_doc(CORPUS / "usgs" / f"{doc_id}.md", {
                        "id": doc_id, "title": title, "material": name, "doc_type": "usgs_mcs",
                        "source": f"U.S. Geological Survey, Mineral Commodity Summaries {year}",
                        "source_url": url, "fetched_at": fetch_date, "synthetic": False,
                        "license": "Public domain (U.S. Government work)",
                    }, body)
                    n += 1
    return n


def build_supplier_docs(fetch_date: str) -> int:
    (ROOT / "data").mkdir(exist_ok=True)
    (ROOT / "data" / "suppliers.json").write_text(json.dumps(
        {"synthetic": True, "note": "FICTIONAL companies for demo purposes", "suppliers": SUPPLIERS,
         "customer": CUSTOMER}, indent=2), encoding="utf-8")
    n = 0
    for s in SUPPLIERS:
        slug = re.sub(r"[^a-z0-9]+", "-", s["company"].lower()).strip("-")
        lines = [f"{s['company']} is a fictional tier-{s['tier']} supplier headquartered in {s['hq']}.",
                 "Material sourcing (share of that material's volume by country of origin):"]
        for m in s["materials"]:
            lines.append(f"- {m['material']}: {m['share_pct']}% sourced from {m['country']}")
        used_by = [p["product"] for p in CUSTOMER["products"] if s["company"] in p["suppliers"]]
        if used_by:
            lines.append(f"Acme Drives (fictional demo customer) buys from {s['company']} for: {', '.join(used_by)}.")
        else:
            lines.append(f"{s['company']} is not currently in Acme Drives' approved supplier list.")
        write_doc(CORPUS / "synthetic" / f"supplier-{slug}.md", {
            "id": f"supplier-{slug}", "title": f"Supplier profile: {s['company']} (fictional)",
            "material": ", ".join(sorted({m['material'] for m in s['materials']})),
            "doc_type": "supplier_profile", "source": "SupplyWatch demo supplier directory (synthetic)",
            "source_url": "data/suppliers.json", "fetched_at": fetch_date, "synthetic": True,
        }, "\n".join(lines))
        n += 1
    bom = ["Acme Drives is a FICTIONAL demo customer. Its bill of materials maps products to suppliers:"]
    for p in CUSTOMER["products"]:
        bom.append(f"- {p['product']}: supplied by {', '.join(p['suppliers'])}")
    write_doc(CORPUS / "synthetic" / "customer-acme-drives-bom.md", {
        "id": "customer-acme-drives-bom", "title": "Acme Drives bill of materials (fictional)",
        "material": "multiple", "doc_type": "customer_bom", "source": "SupplyWatch demo data (synthetic)",
        "source_url": "data/suppliers.json", "fetched_at": fetch_date, "synthetic": True,
    }, "\n".join(bom))
    return n + 1


NEWS_PROMPT = """Write {k} short FICTIONAL trade-news items (80-140 words each) for a supply-chain risk demo.
Use ONLY these fictional companies and facts; do not mention real companies:
{facts}
Each item must contain one concrete, checkable detail (a date in 2026, a percentage, a plant or port
name you invent, or a volume). Topics: shipment delays, plant outages, contract wins, audits,
new sourcing, price changes. Return ONLY JSON: a list of objects with keys "title", "company", "material", "body"."""


def build_synthetic_news(fetch_date: str, k_per_batch: int = 5, batches: int = 6) -> int:
    from core.llm import get_text_llm  # noqa: WPS433 (app module)
    llm = get_text_llm(backend=None, model="claude-haiku-5-5")
    n = 0
    for b in range(batches):
        group = SUPPLIERS[b * 3:(b + 1) * 3]
        facts = "\n".join(f"- {s['company']} (HQ {s['hq']}): " + "; ".join(
            f"{m['material']} from {m['country']} {m['share_pct']}%" for m in s["materials"]) for s in group)
        res = llm.complete(system="You write realistic but clearly fictional demo data. Output JSON only.",
                           prompt=NEWS_PROMPT.format(k=k_per_batch, facts=facts), max_tokens=3000)
        text = res.text
        items = json.loads(text[text.index("["): text.rindex("]") + 1])
        for i, it in enumerate(items):
            doc_id = f"news-synth-{b:02d}-{i:02d}"
            write_doc(CORPUS / "synthetic" / f"{doc_id}.md", {
                "id": doc_id, "title": f"{it['title']} (fictional news)", "material": it.get("material", ""),
                "doc_type": "news", "source": f"LLM-generated synthetic news ({res.model})",
                "source_url": "synthetic://generated", "fetched_at": fetch_date, "synthetic": True,
                "company": it.get("company", ""),
            }, it["body"])
            n += 1
    return n


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--skip-news", action="store_true", help="don't call the LLM (keep existing news docs)")
    args = ap.parse_args()
    today = date.today().isoformat()
    print("usgs docs:", build_usgs(today))
    print("supplier docs:", build_supplier_docs(today))
    if not args.skip_news:
        print("synthetic news docs:", build_synthetic_news(today))
    print("total:", len(list(CORPUS.rglob("*.md"))))
